const PREFS = {
  get lang() { return localStorage.getItem("ss.lang") === "en" ? "en" : "id"; },
  get theme() { const t = localStorage.getItem("ss.theme"); return t === "light" || t === "dark" ? t : "system"; },
};

function applyPrefs() {
  const r = document.documentElement;
  r.lang = PREFS.lang;
  if (PREFS.theme === "system") r.removeAttribute("data-theme"); else r.setAttribute("data-theme", PREFS.theme);
}
applyPrefs();

function t(key, vars) {
  let s = (DICT[PREFS.lang] && DICT[PREFS.lang][key]) ?? DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(String(v));
  return s;
}

// Translate a message that came from the server.
function errText(msg) {
  if (PREFS.lang === "en") return msg;
  if (SERVER_ERR_ID[msg]) return SERVER_ERR_ID[msg];
  let m;
  if ((m = /^(.+) too long$/.exec(msg))) return `${m[1]} terlalu panjang.`;
  if ((m = /^Invalid (.+)$/.exec(msg))) return `${m[1]} tidak valid.`;
  if ((m = /^Provider returned HTTP (\d+): ([\s\S]*)$/.exec(msg))) return `Penyedia AI mengembalikan HTTP ${m[1]}: ${m[2]}`;
  if ((m = /^Could not reach provider: ([\s\S]*)$/.exec(msg))) return `Penyedia AI tidak dapat dijangkau: ${m[1]}`;
  if ((m = /^Unknown provider '(.+)'$/.exec(msg))) return `Penyedia '${m[1]}' tidak dikenal.`;
  return msg;
}

